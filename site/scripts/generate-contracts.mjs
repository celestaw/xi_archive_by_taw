import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import fs from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const root = fileURLToPath(new URL("..", import.meta.url));
const python = process.env.XI_PYTHON ?? resolve(root, "backend/.venv", process.platform === "win32" ? "Scripts/python.exe" : "bin/python");
for (const script of ["export_openapi.py"]) {
  const result = spawnSync(python, [resolve(root, "scripts", script)], { cwd: root, stdio: "inherit" });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
const ast = await openapiTS(new URL("../contracts/openapi.json", import.meta.url));
fs.mkdirSync(resolve(root, "web/lib"), { recursive: true });
fs.writeFileSync(resolve(root, "web/lib/schema.d.ts"), "// Generated by npm run contracts. Do not edit.\n" + astToString(ast));
console.log("Generated web/lib/schema.d.ts");
